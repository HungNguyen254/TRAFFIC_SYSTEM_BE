import httpx
from fastapi import HTTPException, status

from app.core.config import settings


class GeminiService:
    def __init__(self, api_key: str | None = None, model: str | None = None) -> None:
        self.api_key = api_key if api_key is not None else settings.GEMINI_API_KEY
        self.model = model if model is not None else settings.GEMINI_MODEL

    async def generate_response(
        self,
        contents: list[dict],
        system_instruction: str | None = None,
    ) -> str:
        """Call Google Gemini API asynchronously to generate chat response.
        
        Args:
            contents: Multi-turn message list in Gemini format:
                      [{"role": "user" | "model", "parts": [{"text": "..."}]}]
            system_instruction: Optional system prompt instructions.
            
        Returns:
            Text reply generated by the Gemini model.
        """
        if not self.api_key:
            raise HTTPException(
                status_code=status.HTTP_503_SERVICE_UNAVAILABLE,
                detail="GEMINI_API_KEY chưa được cấu hình. Vui lòng thêm GEMINI_API_KEY vào biến môi trường hoặc .env.",
            )

        url = f"https://generativelanguage.googleapis.com/v1beta/models/{self.model}:generateContent"
        headers = {
            "Content-Type": "application/json",
            "x-goog-api-key": self.api_key,
        }
        
        payload: dict = {"contents": contents}
        if system_instruction:
            payload["system_instruction"] = {
                "parts": [{"text": system_instruction}]
            }

        try:
            async with httpx.AsyncClient(timeout=30.0) as client:
                response = await client.post(url, json=payload, headers=headers)
        except httpx.RequestError as exc:
            raise HTTPException(
                status_code=status.HTTP_502_BAD_GATEWAY,
                detail=f"Lỗi kết nối tới Gemini API: {str(exc)}",
            ) from exc

        if response.status_code == 429:
            raise HTTPException(
                status_code=status.HTTP_429_TOO_MANY_REQUESTS,
                detail="Gemini API vượt quá giới hạn yêu cầu (Quota / Rate limit).",
            )

        if response.status_code != 200:
            raise HTTPException(
                status_code=status.HTTP_502_BAD_GATEWAY,
                detail=f"Gemini API trả về lỗi: {response.text}",
            )

        try:
            data = response.json()
            candidates = data.get("candidates", [])
            if not candidates:
                raise ValueError("Không có nội dung phản hồi trong candidates.")
            parts = candidates[0].get("content", {}).get("parts", [])
            if not parts:
                raise ValueError("Không có parts trong content của phản hồi.")
            return parts[0].get("text", "")
        except Exception as exc:
            raise HTTPException(
                status_code=status.HTTP_502_BAD_GATEWAY,
                detail=f"Lỗi phân tích cú pháp phản hồi từ Gemini API: {str(exc)}",
            ) from exc


def get_gemini_service() -> GeminiService:
    """Dependency provider without parameters to prevent FastAPI from exposing GeminiService.__init__ as query parameters."""
    return GeminiService()
